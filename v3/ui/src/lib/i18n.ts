export function t(language: Language, message: Message): string {
  return language === 'zh' ? chinese[message] : message;
}

export function errorText(language: Language, message: string): string {
  return language === 'zh' && Object.hasOwn(chinese, message)
    ? chinese[message as Message] : message;
}

export function protocolLabel(value: string, selectedLanguage: Language): string {
  return selectedLanguage === 'zh' ? protocolChinese[value] ?? value : value;
}

function readLanguage(): Language {
  try { return window.localStorage.getItem(storageKey) === 'zh' ? 'zh' : 'en'; }
  catch { return 'en'; }
}

export const language = writable<Language>(readLanguage());

export function setLanguage(value: Language): void {
  language.set(value);
  document.documentElement.lang = value === 'zh' ? 'zh-CN' : 'en';
  try { window.localStorage.setItem(storageKey, value); }
  catch { /* The selection still applies to this page. */ }
}

export function syncDocumentLanguage(value: Language): void {
  document.documentElement.lang = value === 'zh' ? 'zh-CN' : 'en';
}

import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {once} from 'node:events';
import {createHash} from 'node:crypto';
import {readFile,cp,mkdir,mkdtemp,rm,writeFile} from 'node:fs/promises';
import path from 'node:path';
import {Client} from '@modelcontextprotocol/client';
import {StdioClientTransport} from '@modelcontextprotocol/client/stdio';
import test from 'node:test';
import {freeFetchSafePort} from './fetch-safe-port.mjs';
const repo=path.resolve(import.meta.dirname,'../..');
const binary=process.env.AGENTSESSION_V3_BIN||path.join(repo,'v3/target/debug',process.platform==='win32'?'agentsession-v3.exe':'agentsession-v3');
const fixture=path.join(repo,'v3/fixtures/deepseek-harness-v4');
const session={provider:'deepseek-harness',sessionId:'dsh-v4-parent'};
const digest=b=>createHash('sha256').update(b).digest('hex');

test('DSH v4 native Web and MCP preserve tool content, source events and mailbox pagination', {timeout:30000}, async t=>{
  const work=await mkdtemp(path.join(repo,'tmp/dsh-v4-'));
  const source=path.join(fixture,'sessions/public/dsh-v4-parent/session.v4.jsonl');
  const before=digest(await readFile(source));
  await cp(fixture,path.join(work,'dsh'),{recursive:true});
  await writeFile(path.join(work,'dsh/sessions/public/dsh-v4-parent/session.v3.jsonl'),'unselected prior generation');
  const stateNames=['codex','claude','pi','meta','index','cache'];
  for(const name of stateNames)await mkdir(path.join(work,name));
  const config=path.join(work,'config.json');
  await writeFile(config,'{}');
  const args=['--config',config,'--dsh-dir',path.join(work,'dsh'),'--opencode-db',path.join(work,'missing.db'),...stateNames.flatMap(name=>[`--${name}-dir`,path.join(work,name)])];
  const port=await freeFetchSafePort();
  const child=spawn(binary,['serve','--port',String(port),'--disable-terminal-launch',...args],{cwd:repo,windowsHide:true,stdio:['ignore','ignore','pipe']});
  const closed=once(child,'close');let client;
  t.after(async()=>{if(client)await client.close();child.kill();await closed;assert.equal(digest(await readFile(source)),before);await rm(work,{recursive:true,force:true});});
  const base=`http://127.0.0.1:${port}`;
  for(let i=0;i<200;i++){try{if((await fetch(base+'/api/providers')).ok)break;}catch{}await new Promise(r=>setTimeout(r,50));}
  async function get(suffix){const response=await fetch(base+suffix),body=await response.json();assert.equal(response.status,200,JSON.stringify(body));return body;}
  const reader=await get(`/api/v3/reader/${session.provider}/${session.sessionId}/bootstrap`);
  const protocol=await get(`/api/v3/protocol/${session.provider}/${session.sessionId}?version=3`);
  assert.equal(protocol.validation.ok,true);
  assert.equal(protocol.events.length,14);
  assert.deepEqual(protocol.agentRuns,[]);
  const catalog=protocol.coordination.find(fact=>fact.evidence.provenance.sourceId==='8');
  assert.equal(catalog.kind,'catalog');
  assert.equal(catalog.state,'recorded');
  assert.deepEqual(catalog.toSessionRef,{provider:session.provider,sessionId:'v4-unavailable-child'});
  const relations=await get(`/api/v3/reader/${session.provider}/${session.sessionId}/relations?${new URLSearchParams({cursor:reader.relations.firstCursor})}`);
  assert.deepEqual(relations.childPlacements,[]);
  const relatedCatalog=relations.entries.find(entry=>entry.type==='coordination'&&entry.observation.provenance.sourceId==='8');
  assert.equal(relatedCatalog.observation.kind,'catalog');
  assert.deepEqual(relatedCatalog.observation.toSessionRef,catalog.toSessionRef);
  for(const seq of [2,3,7,12])assert.equal(protocol.events.find(event=>event.id===`event:dsh:${seq}`).readerEvent,null);
  const tool=reader.segments.flatMap(segment=>segment.items).find(item=>item.event.messageId==='v4-call');
  assert.ok(tool);
  const content=await get(`/api/v3/reader/${session.provider}/${session.sessionId}/content?${new URLSearchParams({messageId:'v4-call',segment:'tool',field:'toolOutput',offset:'0',maxChars:'100',revision:reader.revision})}`);
  assert.equal(content.text,'Original tool body 🚀 end.');
  client=new Client({name:'dsh-v4-test',version:'1.0.0'});
  await client.connect(new StdioClientTransport({command:binary,args:['mcp',...args],cwd:repo,stderr:'pipe'}));
  const call=async arguments_=>{const response=await client.callTool({name:'session_team_messages',arguments:arguments_});assert.notEqual(response.isError,true,response.content?.[0]?.text);return response.structuredContent.result;};
  const listed=await call({action:'list',session,limit:1});assert.equal(listed.messages.length,1);assert.equal(listed.nextCursor,null);
  let request={...listed.messages[0].readArguments,maxChars:5},body='',pages=0;
  do{const page=await call(request);body+=page.content.text;request=page.continuation;pages++;}while(request);
  assert.equal(body,'Public mailbox body 🚀 end.');assert.ok(pages>1);
});
